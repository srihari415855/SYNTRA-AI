"""Prompt Context Schemas."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class Message(BaseModel):
    """Individual conversation message representation."""
    role: str = Field(..., description="Message author role: 'system', 'user', 'assistant', or 'tool'")
    content: str = Field(..., description="Message text or serialized payload")
    name: str = Field(default="", description="Optional tool name if role is 'tool' or tool caller")
    tool_calls: List[Dict[str, Any]] = Field(default_factory=list, description="Optional tool calls generated by assistant")


class PromptContext(BaseModel):
    """
    Contract 1: Carries all necessary historical and initial information from the user.
    """
    user_id: str = Field(..., description="Unique identifier for the conversational user.")
    session_id: Optional[str] = Field(default=None, description="Optional unique identifier for the conversation session.")
    history: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="A chronological list of messages, where each dict contains 'role' and 'content'."
    )
    initial_prompt: str = Field(..., description="The raw text input from the user at the start of a turn.")
